    fn render(&mut self, buf: &mut Buffer, area: Rect, data: &ChartData) {
        let color = prims::palette(3);
        let title = if data.title.is_empty() { "Bubble Chart" } else { &data.title };
        let plot = framed(buf, area, title, color);
        if data.series.len() < 3 || data.series[0].values.is_empty() {
            prims::text(buf, plot, 1, "needs x, y, size series", prims::DIM);
            return;
        }
        let xs = &data.series[0].values;
        let ys = &data.series[1].values;
        let sz = &data.series[2].values;
        let x_max = prims::nice_max(xs.iter().cloned().fold(0.0_f64, f64::max));
        let y_max = prims::nice_max(ys.iter().cloned().fold(0.0_f64, f64::max));
        let sz_max = sz.iter().cloned().fold(1.0_f64, f64::max);
        let x_t = ticks(0.0, x_max, 5);
        let y_t = ticks(0.0, y_max, 5);
        let (x_max, y_max) = scale_override(data, x_max, y_max);

        let mut p = Plot::new(plot, 0.0, x_max, 0.0, y_max);
        apply_grid(data, &mut p);
        p.draw_grid(&x_t, &y_t, crate::prims::GRID_LINE);
        for i in 0..xs.len() {
            let (px, py) = p.px(xs[i], ys[i]);
            let r = (sz[i] / sz_max * 4.0).round() as i32 + 1;
            let c = prims::series_color(i, xs.len());
            // filled circle
            for dy in -r..=r {
                for dx in -r..=r {
                    if dx * dx + dy * dy <= r * r {
                        let d = dx * dx + dy * dy;
                        let col = if d <= (r * r) / 3 {
                            Color::White
                        } else if d <= (r * r) * 2 / 3 {
                            c
                        } else {
                            crate::charts::cartesian::shade_dim(c)
                        };
                        p.canvas.set_px(px + dx, py + dy, col);
                    }
                }
            }
        }
        p.render(buf);
        y_labels(buf, &plot, &y_t, p.grid, Color::DarkGray);
        if plot.y + plot.height + 1 < area.y + area.height {
            let lx = plot.x + plot.width / 2 - 5;
            for (i, ch) in "x values →".chars().enumerate() {
                buf[(lx + i as u16, plot.y + plot.height + 1)]
                    .set_symbol(&ch.to_string())
                    .set_style(prims::fg(Color::DarkGray));
            }
        }
    }
